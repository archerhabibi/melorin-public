<?php

namespace App\Services\Core\ServerSelection;

use App\Models\Category;
use App\Models\ServerPanel;

/**
 * قرارداد الگوریتم انتخاب خودکار سرور (بند ۶.۲ و ۶.۳ سند نیازمندی).
 * افزودن معیار جدید (مصرف، سلامت سرور، ظرفیت و ...) یعنی ساخت یک کلاس
 * تازه که این Interface را پیاده می‌کند — بدون تغییر AccountService.
 */
interface ServerSelectionStrategy
{
    /**
     * از میان سرورهای مجاز یک دسته‌بندی، مناسب‌ترین را انتخاب می‌کند.
     *
     * این متد چیزی را رزرو نمی‌کند — فقط یک پیشنهاد است و می‌تواند
     * بلافاصله بعد از خواندنش توسط یک درخواست هم‌زمانِ دیگر منقضی شود
     * (بند ۶۵ سند v2.1). برای رزروِ واقعیِ ضدِ Race از
     * `selectAndReserve()` استفاده کنید.
     */
    public function select(Category $category): ?ServerPanel;

    /**
     * انتخاب و رزروِ اتمیکِ یک واحد ظرفیت در یک قدم (بند ۶۵ — Capacity).
     *
     * بین چند سرورِ واجدِ شرایط (فعال و زیرِ ظرفیت) به ترتیبِ اولویتِ
     * همین Strategy تلاش می‌کند؛ اگر رزروِ گزینه‌ی اول به‌خاطرِ یک رزروِ
     * هم‌زمانِ دیگر شکست بخورد (Race را باخت)، گزینه‌ی بعدی را امتحان
     * می‌کند. اگر هیچ سروری با ظرفیتِ آزاد نماند، null برمی‌گرداند.
     *
     * پنلِ برگشتی همیشه واقعاً یک واحد ظرفیت رزروشده دارد — مسئولیتِ
     * فراخواننده این است که در صورت شکستِ ساخت اکانت،
     * `releaseCapacitySlot()` را روی همان پنل صدا بزند.
     */
    public function selectAndReserve(Category $category): ?ServerPanel;
}
